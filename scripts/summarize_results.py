"""Regenerate final tables and scientific figures from checked benchmark JSON."""

from collections import defaultdict
import json
from pathlib import Path
import statistics

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
METHODS = ["lasso", "classical", "sam2"]
LABELS = {"box": "Box", "lasso": "Translation baseline", "gate": "Flow gate",
          "affine": "Similarity + refinement", "classical": "Classical + recovery", "sam2": "SAM 2.1 Tiny"}
COLORS = ["#6e7880", "#bd7b36", "#24684a"]


def load(name):
    report = json.loads((ROOT / "results" / f"final-{name}.json").read_text())
    if not report.get("complete"):
        raise ValueError(f"The {name} benchmark has not finished")
    return report


def aggregate(runs):
    return {"iou": statistics.mean(run["mean_iou"] for run in runs),
            "leak": statistics.mean(run["mean_leak_rate"] for run in runs),
            "guarded_leak": statistics.mean(run["guarded_output"]["mean_leak_rate"] for run in runs),
            "review": statistics.mean(run["review_frame_fraction"] for run in runs),
            "excess": statistics.mean(run["mean_excess_frame_fraction"] for run in runs),
            "guarded_excess": statistics.mean(run["guarded_output"]["mean_excess_frame_fraction"] for run in runs),
            "fps": statistics.median(run["fps"] for run in runs)}


def table(runs):
    lines = ["| Method | Raw IoU | Raw leak | Guarded leak | Review frames | Raw excess | Guarded excess | Median fps |",
             "|---|---:|---:|---:|---:|---:|---:|---:|"]
    for method in METHODS:
        values = aggregate([run for run in runs if run["method"] == method])
        lines.append(f"| {LABELS[method]} | {values['iou']:.3f} | {values['leak']:.2%} | {values['guarded_leak']:.2%} | {values['review']:.1%} | {values['excess']:.1%} | {values['guarded_excess']:.1%} | {values['fps']:.1f} |")
    return "\n".join(lines)


def main():
    reports = {name: load(name) for name in ("synthetic", "davis", "crosswalk")}
    images = ROOT / "docs/images"
    images.mkdir(exist_ok=True)
    text = ["# Final measured results", "", "Generated by `python scripts/summarize_results.py`. Rates are macro-averages over object sequences, not pooled pixels. All real-video results use 5-pixel prompt slack. Synthetic overview averages all three slack values.", ""]
    fig, axes = plt.subplots(2, 3, figsize=(13, 7), layout="constrained")
    for column, (name, report) in enumerate(reports.items()):
        groups = [[run for run in report["runs"] if run["method"] == method] for method in METHODS]
        values = [aggregate(group) for group in groups]
        titles = {"synthetic": "Synthetic (4 scenarios × 3 slack values)", "davis": "DAVIS (8 sequences / 12 objects)", "crosswalk": "Crosswalk (6 approximate labeled frames)"}
        for row, key in enumerate(("iou", "leak")):
            ax = axes[row, column]
            heights = [value[key] * (100 if key == "leak" else 1) for value in values]
            ax.bar(np.arange(3), heights, color=COLORS, width=.62)
            ax.set_xticks(np.arange(3), ["Translation", "Classical", "SAM 2"])
            ax.set_ylim(0, 105 if key == "leak" else 1.08)
            ax.spines[["top", "right"]].set_visible(False)
            ax.set_axisbelow(True)
            ax.grid(axis="y", alpha=.18)
            if column == 0:
                ax.set_ylabel("Raw mask IoU" if key == "iou" else "Visible-pixel leak after dilation (%)")
            for x, height in enumerate(heights):
                ax.text(x, height + (2 if key == "leak" else .02), f"{height:.1f}%" if key == "leak" else f"{height:.3f}", ha="center", fontsize=10)
        axes[0, column].set_title(titles[name], fontsize=11)
        text += [f"## {name.title()}", "", table(report["runs"]), "",
                 f"Source commit: `{report['environment']['commit']}`. Source digest: `{report['environment']['source_sha256']}`.", ""]
    fig.suptitle("Tracking accuracy and coverage — full-frame guards excluded", fontsize=16)
    fig.savefig(images / "final-comparison.png", dpi=180)
    fig.savefig(images / "final-comparison.svg")
    plt.close(fig)
    text += ["## Synthetic ablation at 5-pixel slack", "", "| Scenario | Method | IoU | Raw leak | Longest leak (frames) |", "|---|---|---:|---:|---:|"]
    for run in reports["synthetic"]["runs"]:
        if run["slack"] == 5:
            text.append(f"| {run['sequence']} | {LABELS[run['method']]} | {run['mean_iou']:.3f} | {run['mean_leak_rate']:.2%} | {run['longest_leak_frames']} |")
    text += ["", "## DAVIS per-object results", "", "| Object | Method | Raw IoU | Raw leak | Worst-frame leak | Longest leak (frames) |", "|---|---|---:|---:|---:|---:|"]
    for run in reports["davis"]["runs"]:
        text.append(f"| {run['sequence']} | {LABELS[run['method']]} | {run['mean_iou']:.3f} | {run['mean_leak_rate']:.2%} | {run['worst_leak_rate']:.1%} | {run['longest_leak_frames']} |")
    (ROOT / "docs/results.md").write_text("\n".join(text) + "\n", encoding="utf-8")
    print("Wrote docs/results.md and docs/images/final-comparison.{png,svg}")


if __name__ == "__main__":
    main()
